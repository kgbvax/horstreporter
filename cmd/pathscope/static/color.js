const MIN = -3;
const MAX = 6;

const N = ROCKET.length;
const RANGE = MAX - MIN;
const HEX = (n) => n.toString(16).padStart(2, '0');

// scoreToColor maps a z-score to a rocket hex string. NaN falls back
// to the table midpoint so the cell renders something instead of
// breaking the DOM. Out-of-range scores clamp to the endpoints.
export function scoreToColor(score) {
  if (!Number.isFinite(score)) return rocketAt(0.5);
  if (score <= MIN) return rocketAt(0);
  if (score >= MAX) return rocketAt(1);
  return rocketAt((score - MIN) / RANGE);
}

// rocketAt exposes the raw t ∈ [0, 1] lookup so future widgets (a
// probability badge, an opacity ramp) can share the same palette.
export function rocketAt(t) {
  const x = t < 0 ? 0 : t > 1 ? 1 : t;
  const rgb = ROCKET[Math.min(N - 1, Math.round(x * (N - 1)))];
  return `#${HEX((rgb >> 16) & 0xff)}${HEX((rgb >> 8) & 0xff)}${HEX(rgb & 0xff)}`;
}

